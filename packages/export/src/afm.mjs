const TABLES = [ROMAN, ITALIC, BOLD];

/** @param {number} cp @param {number} face 0 roman, 1 italic, 2 bold */
function charWidth(cp, face) {
  if (cp >= 32 && cp <= 126) return TABLES[face][cp - 32];
  const extra = EXTRA.get(cp);
  if (extra) return extra[face];
  // accented Latin letters share the width of the base letter
  const base = String.fromCodePoint(cp).normalize('NFD')[0];
  const b = base.codePointAt(0) ?? 0;
  if (b >= 32 && b <= 126 && base !== String.fromCodePoint(cp)) return TABLES[face][b - 32];
  return 500;
}

/** @type {Map<string, number>} */
const CACHE = new Map();

/**
 * Width of `text` (already restricted to WinAnsi characters) in points at `size`.
 * @param {string} text @param {number} face 0 roman, 1 italic, 2 bold @param {number} size
 */
export function textWidth(text, face, size) {
  let units = 0;
  for (const ch of text) {
    const key = `${face}${ch}`;
    let w = CACHE.get(key);
    if (w === undefined) {
      w = charWidth(/** @type {number} */ (ch.codePointAt(0)), face);
      CACHE.set(key, w);
    }
    units += w;
  }
  return (units * size) / 1000;
}
