// review-request: a Markdown work order that tells the orchestrator which reviewer agents to run on the
// generated pack, with their inputs and expected output files. The adapter never runs an LLM.
import path from 'node:path';
import { isFileSync, listFiles } from './io.mjs';
import { pad2 } from './pack.mjs';

/**
 * @param {{ framework: string, workId: string, chapter: number }} o
 * @returns {string}
 */
export function renderReviewRequest({ framework, workId, chapter }) {
  const nn = pad2(chapter);
  const work = `.work/${workId}`;
  const workAbs = path.join(framework, '.work', workId);
  const exists = (rel) => isFileSync(path.join(workAbs, ...rel.split('/')));
  const mark = (rel) => (exists(rel) ? `${work}/${rel}` : `${work}/${rel} (not generated yet)`);
  const glob = (dir) => {
    const names = listFiles(path.join(workAbs, 'context', dir)).filter((f) => f.endsWith('.md'));
    return names.length > 0 ? names.map((f) => `${work}/context/${dir}/${f}`) : [`${work}/context/${dir}/*.md (none generated)`];
  };
  const rules = (...names) => names.map((r) => `rules/${r}`);
  const candidate = mark(`candidate/chapter-${nn}-candidate.md`);

  const reviewers = [
    {
      name: 'style-linter',
      kind: 'style',
      inputs: [candidate, mark('context/style.md'), mark('context/book.md'), mark(`reports/chapter-${nn}-style-tech-report.md`), ...rules('README.md', 'writing.md', 'review-checklist.md')],
    },
    {
      name: 'character-reviewer',
      kind: 'character',
      inputs: [candidate, ...glob('characters'), ...glob('knowledge'), mark('context/state/current/characters.md'), ...rules('README.md', 'characters.md', 'review-checklist.md')],
    },
    {
      name: 'continuity-reviewer',
      kind: 'continuity',
      inputs: [
        candidate,
        mark('context/state/current/situation.md'), mark('context/state/current/knowledge.md'), mark('context/state/current/inventory.md'),
        mark('context/timeline/history.md'), mark('context/continuity-check.md'), mark('context/ledger.md'),
        mark('context/state-events.md'), mark('context/previous-chapter.md'),
        ...glob('locations'), ...glob('objects'), ...glob('factions'), ...glob('lore'),
        ...rules('README.md', 'world-building.md', 'review-checklist.md'),
      ],
    },
  ];

  const lines = [
    `# Review request - chapter ${nn}`,
    '',
    `Generated by sf-claude-book (adapter version 1) for work folder \`${work}/\`. Paths are relative to the Claude-Book root. Run the reviewers below in parallel; the adapter does not run them.`,
    '',
  ];
  for (const r of reviewers) {
    const agent = `analysis/.claude/agents/${r.name}.md`;
    lines.push(
      `## ${r.name}`,
      '',
      `- Agent: ${isFileSync(path.join(framework, ...agent.split('/'))) ? agent : `${agent} (not found)`}`,
      '- Inputs:',
      ...r.inputs.map((i) => `  - ${i}`),
      `- Expected output: ${work}/chapter-${nn}-${r.kind}-report.md`,
      '',
    );
  }
  return lines.join('\n');
}
