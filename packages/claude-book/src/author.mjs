// plan and co-write texts (contract M05-J06 section 3). Pure; the adapter never runs a model.
import path from 'node:path';
import { isFileSync, listFiles } from './io.mjs';
import { pad2 } from './pack.mjs';

/**
 * plan-request: a Markdown work order for the chapter-planner agent with its inputs and expected output.
 * @param {{ framework: string, workId: string, chapter: number }} o
 */
export function renderPlanRequest({ framework, workId, chapter }) {
  const nn = pad2(chapter);
  const work = `.work/${workId}`;
  const workAbs = path.join(framework, '.work', workId);
  const mark = (rel) => (isFileSync(path.join(workAbs, ...rel.split('/'))) ? `${work}/${rel}` : `${work}/${rel} (not generated)`);
  const agent = 'analysis/.claude/agents/chapter-planner.md';
  const rules = ['README.md', 'writing.md', 'characters.md', 'world-building.md', 'review-checklist.md'].map((r) => `rules/${r}`);
  const known = listFiles(path.join(workAbs, 'context')).length > 0;
  return [
    `# Plan request - chapter ${nn}`,
    '',
    `Generated by sf-claude-book (adapter version 1) for work folder \`${work}/\`. Paths are relative to the Claude-Book root. Run the planner below; the adapter does not run it.`,
    '',
    '## chapter-planner',
    '',
    `- Agent: ${isFileSync(path.join(framework, ...agent.split('/'))) ? agent : `${agent} (not found)`}`,
    `- Chapter number: ${chapter}`,
    '- Inputs:',
    ...['synopsis.md', 'plan.md', 'state/current/situation.md', 'previous-chapter.md', 'entries-index.md', 'ledger.md'].map((f) => `  - ${mark(`context/${f}`)}`),
    ...rules.map((r) => `  - ${r}`),
    `- Expected output: ${work}/chapter-${nn}-plan.md`,
    '',
    known ? 'The context pack was rebuilt for this chapter by the same command.' : 'No context pack found.',
    '',
  ].join('\n');
}

/**
 * The draft copy with a header that marks it as a proposal. The header is an HTML comment, so it never becomes story text.
 * @param {{ chapter: number, from: string, sha256: string, text: string }} o
 */
export function renderCoWriteDraft({ chapter, from, sha256, text }) {
  return [
    `<!-- sf-claude-book co-write: PROPOSAL for chapter ${pad2(chapter)} -->`,
    '<!-- Not canonical and not applied to the book. The author decides what, if anything, goes into the manuscript. -->',
    `<!-- source: ${path.basename(from)} (sha256 ${sha256}) -->`,
    '',
    text,
  ].join('\n');
}
