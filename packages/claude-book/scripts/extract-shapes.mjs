#!/usr/bin/env node
// extract-shapes <kethra context folder> [out file]
// Reads a Claude-Book context pack and records ONLY key names and value types of its JSON-object files
// (entries-index.md, ledger.md, state-events.md, knowledge/*.md). No text value is ever written.
// Output default: packages/claude-book/shapes/kethra-context-shapes.json
//
// Shape language: a scalar type is "string" | "number" | "boolean" | "null" (unions joined with "|", sorted);
// an array is { "array": <shape of its items, or "empty" if no item was seen> }; an object is { "object": { key: shape } }.
// Per file: { "objects": <how many objects were seen>, "keys": { key: shape }, "optional": [keys not in every object] }.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseConcatenatedJson } from '../src/json-stream.mjs';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const [src, outArg] = process.argv.slice(2);
if (!src) {
  process.stderr.write('usage: extract-shapes <context folder> [out file]\n');
  process.exit(2);
}
const out = outArg ?? path.join(HERE, '..', 'shapes', 'kethra-context-shapes.json');

const tag = (v) => (v === null ? 'null' : Array.isArray(v) ? 'array' : typeof v);

/** Merge the shapes of many values into one. @param {unknown[]} values */
function shapeOf(values) {
  if (values.length === 0) return 'empty';
  const scalars = new Set();
  const arrays = [];
  const objects = [];
  for (const v of values) {
    const t = tag(v);
    if (t === 'array') arrays.push(...v.map((x) => x));
    else if (t === 'object') objects.push(v);
    else scalars.add(t);
  }
  const parts = [...scalars];
  const isArray = values.some((v) => Array.isArray(v));
  const isObject = objects.length > 0;
  if ([parts.length > 0, isArray, isObject].filter(Boolean).length > 1) {
    // Mixed structural and scalar values: record every alternative's tag only.
    return [...parts, ...(isArray ? ['array'] : []), ...(isObject ? ['object'] : [])].sort().join('|');
  }
  if (isArray) return { array: shapeOf(arrays) };
  if (isObject) return { object: keysOf(objects) };
  return parts.sort().join('|');
}

/** @param {object[]} objects */
function keysOf(objects) {
  const names = [...new Set(objects.flatMap((o) => Object.keys(o)))].sort();
  return Object.fromEntries(names.map((k) => [k, shapeOf(objects.filter((o) => Object.hasOwn(o, k)).map((o) => o[k]))]));
}

function describe(files) {
  const objects = files.flatMap((f) => parseConcatenatedJson(fs.readFileSync(f, 'utf8')));
  const keys = keysOf(objects);
  const optional = Object.keys(keys).filter((k) => objects.some((o) => !Object.hasOwn(o, k)));
  return { objects: objects.length, keys, optional };
}

const dir = path.resolve(src);
const knowledgeDir = path.join(dir, 'knowledge');
const knowledge = fs.existsSync(knowledgeDir)
  ? fs.readdirSync(knowledgeDir).filter((f) => f.endsWith('.md')).sort().map((f) => path.join(knowledgeDir, f))
  : [];
const shapes = {
  note: 'Key names and value types only, generated by scripts/extract-shapes.mjs from a Claude-Book context pack. No text values.',
  files: {
    'entries-index.md': describe([path.join(dir, 'entries-index.md')]),
    'ledger.md': describe([path.join(dir, 'ledger.md')]),
    'state-events.md': describe([path.join(dir, 'state-events.md')]),
    'knowledge/<slug>.md': describe(knowledge),
  },
};
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, `${JSON.stringify(shapes, null, 2)}\n`);
process.stdout.write(`wrote ${out}\n`);
